import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { Connection, Keypair, clusterApiUrl } from '@solana/web3.js';
import { createMint, getOrCreateAssociatedTokenAccount, mintTo } from '@solana/spl-token';

const rpcUrl = process.env.SOLANA_RPC_URL || clusterApiUrl('devnet');
const keypairPath = process.env.SOLANA_KEYPAIR;

if (!keypairPath) {
  throw new Error('Set SOLANA_KEYPAIR to a funded Devnet keypair JSON path.');
}

const secret = JSON.parse(fs.readFileSync(path.resolve(keypairPath), 'utf8'));
const payer = Keypair.fromSecretKey(Uint8Array.from(secret));
const connection = new Connection(rpcUrl, 'confirmed');

const assets = [
  { env: 'VITE_DEVNET_CASH_MINT', name: 'Demo USDC', symbol: 'DEMO-USDC', decimals: 6, supply: 1_000_000_000 },
  { env: 'VITE_DEVNET_NVDA_MINT', name: 'NVIDIA synthetic demo asset', symbol: 'NVDAx-DEMO', decimals: 6, supply: 10_000_000 },
  { env: 'VITE_DEVNET_AAPL_MINT', name: 'Apple synthetic demo asset', symbol: 'AAPLx-DEMO', decimals: 6, supply: 10_000_000 },
  { env: 'VITE_DEVNET_MSFT_MINT', name: 'Microsoft synthetic demo asset', symbol: 'MSFTx-DEMO', decimals: 6, supply: 10_000_000 },
  { env: 'VITE_DEVNET_GOOG_MINT', name: 'Alphabet synthetic demo asset', symbol: 'GOOGx-DEMO', decimals: 6, supply: 10_000_000 },
];

console.log(`Using payer: ${payer.publicKey.toBase58()}`);

const lines = [];
for (const asset of assets) {
  const mint = await createMint(connection, payer, payer.publicKey, payer.publicKey, asset.decimals);
  const account = await getOrCreateAssociatedTokenAccount(connection, payer, mint, payer.publicKey);
  const baseUnits = BigInt(asset.supply) * 10n ** BigInt(asset.decimals);
  await mintTo(connection, payer, mint, account.address, payer, baseUnits);

  console.log(`${asset.symbol}: ${mint.toBase58()}`);
  console.log(`  demo supply seeded to payer ATA: ${account.address.toBase58()}`);
  lines.push(`${asset.env}=${mint.toBase58()}`);
}

const out = path.resolve(process.env.ENV_OUTPUT || '.env.devnet');
fs.writeFileSync(out, `# Generated by scripts/create-devnet-assets.mjs\n${lines.join('\n')}\n`);
console.log(`\nWrote mint configuration to ${out}`);
