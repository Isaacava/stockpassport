import { Connection, Keypair, clusterApiUrl } from '@solana/web3.js';
import { AuthorityType, createMint, getOrCreateAssociatedTokenAccount, mintTo, setAuthority } from '@solana/spl-token';
import fs from 'node:fs/promises';

const rpcUrl = process.env.DEVNET_RPC_URL || process.env.SOLANA_RPC_URL || clusterApiUrl('devnet');
const privateKey = process.env.DEVNET_MARKET_PRIVATE_KEY;
const expectedMarketWallet = process.env.DEVNET_MARKET_WALLET?.trim() || '';
const outputFile = process.env.ENV_OUTPUT || '.env.devnet';
const SUPPLY = 1_000_000_000n;
const DECIMALS = 6;

if (!privateKey) throw new Error('Set DEVNET_MARKET_PRIVATE_KEY to the base58 Devnet market-wallet private key.');

function decodeBase58(value) {
  const alphabet = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
  const indexes = new Map(alphabet.split('').map((char, index) => [char, index]));
  let bytes = [0];
  for (const char of value.trim()) {
    const digit = indexes.get(char);
    if (digit === undefined) throw new Error('Invalid base58 private key');
    let carry = digit;
    for (let i = 0; i < bytes.length; i += 1) {
      const next = bytes[i] * 58 + carry;
      bytes[i] = next & 0xff;
      carry = next >> 8;
    }
    while (carry > 0) {
      bytes.push(carry & 0xff);
      carry >>= 8;
    }
  }
  let leadingZeros = 0;
  while (leadingZeros < value.length && value[leadingZeros] === '1') leadingZeros += 1;
  const decoded = new Uint8Array(leadingZeros + bytes.length);
  for (let i = 0; i < bytes.length; i += 1) decoded[decoded.length - 1 - i] = bytes[i];
  return decoded;
}

const market = Keypair.fromSecretKey(decodeBase58(privateKey));
if (expectedMarketWallet && market.publicKey.toBase58() !== expectedMarketWallet) {
  throw new Error(`Market wallet mismatch: private key resolves to ${market.publicKey.toBase58()}`);
}

const connection = new Connection(rpcUrl, 'confirmed');
const assets = [
  { env: 'VITE_DEVNET_CASH_MINT', serverEnv: 'DEVNET_CASH_MINT', symbol: 'DEMO-USDC' },
  { env: 'VITE_DEVNET_NVDA_MINT', serverEnv: 'DEVNET_NVDA_MINT', symbol: 'NVDAx-DEMO' },
  { env: 'VITE_DEVNET_AAPL_MINT', serverEnv: 'DEVNET_AAPL_MINT', symbol: 'AAPLx-DEMO' },
  { env: 'VITE_DEVNET_MSFT_MINT', serverEnv: 'DEVNET_MSFT_MINT', symbol: 'MSFTx-DEMO' },
  { env: 'VITE_DEVNET_GOOG_MINT', serverEnv: 'DEVNET_GOOG_MINT', symbol: 'GOOGx-DEMO' },
];

console.log(`Market wallet: ${market.publicKey.toBase58()}`);
console.log(`Network: ${rpcUrl}`);
console.log(`Fixed supply per token: ${SUPPLY.toString()}`);

const lines = [
  '# Generated by scripts/create-devnet-assets.mjs',
  `# Fixed supply per token: ${SUPPLY.toString()}`,
  `DEVNET_MARKET_WALLET=${market.publicKey.toBase58()}`,
];

for (const asset of assets) {
  console.log(`Creating ${asset.symbol}...`);
  const mint = await createMint(connection, market, market.publicKey, null, DECIMALS);
  const marketAccount = await getOrCreateAssociatedTokenAccount(connection, market, mint, market.publicKey);
  const rawSupply = SUPPLY * 10n ** BigInt(DECIMALS);
  await mintTo(connection, market, mint, marketAccount.address, market.publicKey, rawSupply);
  await setAuthority(connection, market, mint, market.publicKey, AuthorityType.MintTokens, null);
  const mintAddress = mint.toBase58();
  console.log(`${asset.symbol}: ${mintAddress}`);
  console.log(`  market ATA: ${marketAccount.address.toBase58()}`);
  lines.push(`${asset.env}=${mintAddress}`);
  lines.push(`${asset.serverEnv}=${mintAddress}`);
}

lines.push('');
await fs.writeFile(outputFile, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote mint configuration to ${outputFile}`);
console.log('Mint authority revoked for every asset.');
