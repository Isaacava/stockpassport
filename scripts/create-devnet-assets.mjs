import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { Connection, Keypair, clusterApiUrl } from '@solana/web3.js';
import {
  AuthorityType,
  createMint,
  getOrCreateAssociatedTokenAccount,
  mintTo,
  setAuthority,
} from '@solana/spl-token';

const rpcUrl = process.env.SOLANA_RPC_URL || process.env.DEVNET_RPC_URL || clusterApiUrl('devnet');
const MARKET_WALLET = process.env.DEVNET_MARKET_WALLET;
const privateKey = process.env.DEVNET_MARKET_PRIVATE_KEY;
const keypairJson = process.env.DEVNET_MARKET_KEYPAIR_JSON;

const ALPHABET = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
const INDEX = new Map(ALPHABET.split('').map((char, index) => [char, index]));

function decodeBase58(value) {
  const text = value.trim();
  if (!text) throw new Error('Empty base58 private key');

  let bytes = [0];
  for (const char of text) {
    const digit = INDEX.get(char);
    if (digit === undefined) throw new Error('Invalid base58 private key');
    let carry = digit;
    for (let i = 0; i < bytes.length; i += 1) {
      const next = bytes[i] * 58 + carry;
      bytes[i] = next & 0xff;
      carry = next >> 8;
    }
    while (carry > 0) {
      bytes.push(carry & 0xff);
      carry >>= 8;
    }
  }

  let leadingZeros = 0;
  while (leadingZeros < text.length && text[leadingZeros] === '1') leadingZeros += 1;
  const decoded = new Uint8Array(leadingZeros + bytes.length);
  for (let i = 0; i < bytes.length; i += 1) decoded[decoded.length - 1 - i] = bytes[i];
  return decoded;
}

function loadMarketKeypair() {
  if (privateKey) return Keypair.fromSecretKey(decodeBase58(privateKey));
  if (keypairJson) return Keypair.fromSecretKey(Uint8Array.from(JSON.parse(keypairJson)));
  throw new Error('Set DEVNET_MARKET_PRIVATE_KEY or DEVNET_MARKET_KEYPAIR_JSON.');
}

const market = loadMarketKeypair();
if (MARKET_WALLET && market.publicKey.toBase58() !== MARKET_WALLET) {
  throw new Error('DEVNET_MARKET_WALLET does not match the supplied market key.');
}

const connection = new Connection(rpcUrl, 'confirmed');

const assets = [
  { env: 'CASH', name: 'Demo USDC', symbol: 'DEMO-USDC', decimals: 6, supply: 1_000_000_000n },
  { env: 'NVDA', name: 'NVIDIA synthetic demo asset', symbol: 'NVDAx-DEMO', decimals: 6, supply: 1_000_000_000n },
  { env: 'AAPL', name: 'Apple synthetic demo asset', symbol: 'AAPLx-DEMO', decimals: 6, supply: 1_000_000_000n },
  { env: 'MSFT', name: 'Microsoft synthetic demo asset', symbol: 'MSFTx-DEMO', decimals: 6, supply: 1_000_000_000n },
  { env: 'GOOG', name: 'Alphabet synthetic demo asset', symbol: 'GOOGx-DEMO', decimals: 6, supply: 1_000_000_000n },
];

console.log(`Using market wallet: ${market.publicKey.toBase58()}`);
const lines = [`# Generated by scripts/create-devnet-assets.mjs`, `DEVNET_MARKET_WALLET=${market.publicKey.toBase58()}`];

for (const asset of assets) {
  const mint = await createMint(connection, market, market.publicKey, market.publicKey, asset.decimals);
  const account = await getOrCreateAssociatedTokenAccount(connection, market, mint, market.publicKey);
  const baseUnits = asset.supply * 10n ** BigInt(asset.decimals);

  await mintTo(connection, market, mint, account.address, market.publicKey, baseUnits);
  await setAuthority(connection, market, mint, market.publicKey, AuthorityType.MintTokens, null);
  await setAuthority(connection, market, mint, market.publicKey, AuthorityType.FreezeAccount, null);

  console.log(`${asset.symbol}: ${mint.toBase58()}`);
  console.log(`  full supply: ${asset.supply.toString()}`);
  console.log(`  market ATA: ${account.address.toBase58()}`);

  lines.push(`VITE_DEVNET_${asset.env === 'CASH' ? 'CASH' : asset.env}_MINT=${mint.toBase58()}`);
  lines.push(`DEVNET_${asset.env === 'CASH' ? 'CASH' : asset.env}_MINT=${mint.toBase58()}`);
}

const out = path.resolve(process.env.ENV_OUTPUT || '.env.devnet');
fs.writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`\nWrote mint configuration to ${out}`);
console.log('Mint authority and freeze authority were revoked for every token.');
